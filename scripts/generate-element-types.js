#!/usr/bin/env node
/**
 * generate-element-types.js - write src/types/elements.generated.d.ts: one
 * HTMLElementTagNameMap entry per custom element LCARdS registers.
 *
 * TypeScript types document.createElement('lcards-chart') and
 * querySelector('lcards-chart') through HTMLElementTagNameMap. Without an entry
 * it falls back to plain HTMLElement and every card property (`.hass`,
 * `.setConfig`) is an error. This scans every customElements.define('<tag>',
 * <Class>) call in src/ and maps the tag to the class's file.
 *
 *   node scripts/generate-element-types.js           # write the file
 *   node scripts/generate-element-types.js --check   # exit 1 if it is stale (tests use this)
 *
 * Home Assistant's own elements (ha-dialog, hui-card, ...) are declared by hand in
 * src/types/ha-elements.d.ts. A tag whose class isn't exported is left out (named in
 * a comment at the top of the output).
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const OUT = join(SRC, 'types/elements.generated.d.ts');

const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap(e =>
  e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith('.js') ? [join(dir, e.name)] : []);

/** @returns {string} the d.ts text for the current source tree */
export function buildElementTypes() {
  const files = walk(SRC).map(file => ({ file, text: readFileSync(file, 'utf8') }));
  const DEFINE = /customElements\.define\(\s*['"]([a-z0-9-]+)['"]\s*,\s*([A-Za-z_$][\w$]*)\s*\)/g;
  /** @type {Map<string, string>} tag -> class */
  const tags = new Map();
  for (const { text } of files) {
    for (const [, tag, cls] of text.matchAll(DEFINE)) tags.set(tag, cls);
  }
  /** Where each class is exported from (export class X / export { X }). */
  const exportedFrom = (cls) => files.find(({ text }) =>
    new RegExp(`export\\s+(?:default\\s+)?class\\s+${cls}\\b`).test(text) ||
    new RegExp(`export\\s*\\{[^}]*\\b${cls}\\b[^}]*\\}`).test(text))?.file;

  const lines = [];
  /** Registered with a class no file exports (internal helpers): left out, still HTMLElement. */
  const skipped = [];
  for (const tag of [...tags.keys()].sort()) {
    const cls = tags.get(tag);
    const file = exportedFrom(cls);
    if (!file) { skipped.push(tag); continue; }
    const rel = relative(dirname(OUT), file).replace(/\\/g, '/');
    lines.push(`        '${tag}': import('${rel.startsWith('.') ? rel : './' + rel}').${cls};`);
  }
  const note = skipped.length ? `// Not listed (class not exported): ${skipped.join(', ')}\n` : '';
  return `// Generated by scripts/generate-element-types.js: do not edit. Run it again after
// adding or renaming a custom element (tests/core/element-types.test.js checks this file is current).
${note}export {};

declare global {
    interface HTMLElementTagNameMap {
${lines.join('\n')}
    }
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = buildElementTypes();
  if (process.argv.includes('--check')) {
    const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
    if (current !== text) {
      console.error(`${relative(ROOT, OUT)} is stale: run node scripts/generate-element-types.js`);
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`✅ Wrote ${relative(ROOT, OUT)} (${text.split('\n').filter(l => l.includes("': import(")).length} elements)`);
  }
}
