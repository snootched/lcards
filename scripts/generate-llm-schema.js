#!/usr/bin/env node
/**
 * @fileoverview Generate the published LCARdS JSON Schemas, for LLMs and editors
 * so they stop inventing config keys.
 *
 * Pulls the real JSON Schemas from `scripts/lib/card-schemas.js`, the same list
 * `scripts/validate-doc-examples.js` validates doc examples against, so the
 * published schema can never drift from what the app validates against. The
 * packing (stripping editor metadata, shared files, $defs) is in
 * `scripts/lib/schema-publish.js`.
 *
 * Output, under the output folder (default doc/public/, served at the docs site
 * root; gitignored, regenerated by docs:build, docs:serve and the Release workflow):
 *
 *   lcards-schema.json                 everything in one file (cards incl. MSD, views, strategies)
 *   schema/index.json                  what exists, sizes, which shared files each one uses
 *   schema/cards/<tag>.json            one card, self-contained apart from shared/ refs
 *   schema/views/<tag>.json            view types (lcards-layout-view)
 *   schema/strategies/<tag>.json       dashboard strategies (lcars-shell)
 *   schema/shared/<name>.json          rules, animation, background-animation, state-color, filter
 *
 * Usage:
 *   node scripts/generate-llm-schema.js
 *   node scripts/generate-llm-schema.js --out-dir=<dir>   # write elsewhere (tests, Release workflow)
 */

import { getSchemaEntries } from './lib/card-schemas.js';
import { buildSchemaSet }   from './lib/schema-publish.js';

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const REPO_ROOT  = path.resolve(path.dirname(__filename), '..');
const outArg     = process.argv.slice(2).find(a => a.startsWith('--out-dir='));
const OUT_DIR    = outArg ? path.resolve(outArg.slice('--out-dir='.length)) : path.join(REPO_ROOT, 'doc', 'public');
const SCHEMA_DIR = path.join(OUT_DIR, 'schema');
const BUNDLE     = path.join(OUT_DIR, 'lcards-schema.json');

const pkg = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf8'));
const { files, bundle, index } = buildSchemaSet(getSchemaEntries(), { version: pkg.version });

// Compact (no indentation): these files are for LLMs and tools to ingest; pretty-
// printing roughly triples their size (and token cost). Use `jq` to read one.
const write = (file, doc) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(doc) + '\n');
};

fs.rmSync(SCHEMA_DIR, { recursive: true, force: true }); // drop files for removed cards
write(BUNDLE, bundle);
write(path.join(SCHEMA_DIR, 'index.json'), index);
for (const [rel, doc] of files) write(path.join(SCHEMA_DIR, rel), doc);

const kb = (file) => (fs.statSync(file).size / 1024).toFixed(1);
const counts = ['cards', 'views', 'strategies', 'shared'].map(s => `${Object.keys(index[s]).length} ${s}`).join(', ');
const largest = [...files.keys()]
  .filter(rel => !rel.startsWith('shared/'))
  .map(rel => [rel, fs.statSync(path.join(SCHEMA_DIR, rel)).size])
  .sort((a, b) => b[1] - a[1])[0];
const show = (p) => (path.relative(REPO_ROOT, p).startsWith('..') ? p : path.relative(REPO_ROOT, p));
console.log(`✅ Wrote ${show(BUNDLE)} (${kb(BUNDLE)} KB) and ${show(SCHEMA_DIR)}/ (${counts}; largest ${largest[0]} ${(largest[1] / 1024).toFixed(1)} KB)`);
