/**
 * The generated part of doc/cards/astrometrics/starters.md: every starter of
 * the astrometrics card with its settings and the YAML it gives with its
 * defaults (a live card per starter). Written by
 * scripts/generate-astro-starters-doc.js; tests/docs/astro-starters-doc.test.js
 * fails when the page and the starters drift.
 */
import { STARTERS, applyStarter } from '../../src/core/astrometrics/starters/index.js';
import { starterYaml } from '../../src/core/astrometrics/starters/yaml.js';

export const BEGIN = '<!-- starters:begin (generated by npm run docs:astro-starters, do not edit) -->';
export const END = '<!-- starters:end -->';

const TYPE = 'custom:lcards-astrometrics-card';

/** A param default as the Studio's field shows it */
const shown = (/** @type {any} */ v) => (Array.isArray(v) ? v.join(', ') : String(v));

/** @param {import('../../src/core/astrometrics/starters/index.js').Starter} s */
function section(s) {
  const out = applyStarter({ type: TYPE, height: 400 }, s);
  if (!out.config) throw new Error(`starter ${s.id}: ${out.error}`);
  const lines = [`### ${s.title}`, '', s.description, ''];
  const params = s.params.filter((p) => p.key !== 'prefix');
  if (s.kind === 'part') {
    const prefix = s.params.find((p) => p.key === 'prefix');
    lines.push(`Its ids start with its name (default \`${prefix?.default}_\`).`, '');
  }
  if (params.length) {
    lines.push('| Setting | Default | Notes |', '|---|---|---|');
    for (const p of params) lines.push(`| ${p.label} | \`${shown(p.default)}\` | ${p.helper ?? ''} |`);
    lines.push('');
  }
  lines.push('```yaml live', starterYaml(out.config).trimEnd(), '```', '');
  return lines.join('\n');
}

/** The markdown between BEGIN and END */
export function startersDoc() {
  const scenes = STARTERS.filter((s) => s.kind === 'scene');
  const parts = STARTERS.filter((s) => s.kind === 'part');
  return [
    '## Scenes', '',
    ...scenes.map(section),
    '## Parts', '',
    'Each part on its own card, at its default centre. In the Studio, give it a point of your scene as its centre.', '',
    ...parts.map(section)
  ].join('\n').trimEnd();
}

/**
 * The page with its generated part replaced.
 * @param {string} page
 */
export function withStartersDoc(page) {
  const a = page.indexOf(BEGIN);
  const b = page.indexOf(END);
  if (a === -1 || b < a) throw new Error('starters.md has no starters:begin / starters:end markers');
  return `${page.slice(0, a + BEGIN.length)}\n\n${startersDoc()}\n\n${page.slice(b)}`;
}
