/**
 * @fileoverview The built-in names a config can refer to: presets, components,
 * animation and background presets, filters, sound events, MSD backgrounds,
 * theme tokens, the HA-LCARS `--lcars-*` and LCARdS palette `--lcards-*` variables. Published as `schema/registries.json` (scripts/generate-llm-schema.js)
 * and used by scripts/lib/config-validator.js to catch values that pass the JSON
 * Schema but don't exist (`preset: lozange`, `theme:colors.ui.primry`).
 *
 * Read from the same modules the runtime registers from. Some of them touch
 * `window` and `__LCARDS_VERSION__` at import time, so those are set up first
 * (as tests/setup/browser-shims.js does for the tests).
 *
 * These are the built-in names; user packs can add presets, components and
 * tokens at runtime, so validators report unknown names as warnings.
 */

import { readFileSync } from 'node:fs';
import { BUILTIN_OPTIONS } from './card-schemas.js';
import { flattenKeys, THEME_PATH_ALLOWED_PREFIXES } from './theme-token-rules.js';

const pkg = JSON.parse(readFileSync(new URL('../../package.json', import.meta.url), 'utf8'));
// The HA-LCARS snapshot (scripts/sync-ha-lcars.js), committed so this stays offline.
const haLcars = JSON.parse(readFileSync(new URL('../data/ha-lcars/snapshot.json', import.meta.url), 'utf8'));

/** @returns {Promise<object>} registries, every list sorted */
export async function buildRegistries() {
  globalThis.window ??= globalThis;
  globalThis.__LCARDS_VERSION__ ??= pkg.version;
  globalThis.requestAnimationFrame ??= (fn) => setTimeout(fn, 16);
  globalThis.cancelAnimationFrame ??= (id) => clearTimeout(id);
  // Node 26's experimental global localStorage warns on first access; nothing here needs it.
  if (Object.getOwnPropertyDescriptor(globalThis, 'localStorage')?.get) {
    Object.defineProperty(globalThis, 'localStorage', { value: undefined, configurable: true, writable: true });
  }

  const src = (p) => new URL(`../../src/${p}`, import.meta.url).href;
  const [{ components }, { BACKGROUND_PRESETS }, { listAnimationPresets }, animations,
    { FILTER_PARAMS_SCHEMAS }, { BUILTIN_SOUNDS_PACK }, { BUILTIN_MSD_SVG_PACK }, { lcardsDefaultTokens }, { GREEN_ALERT_PALETTE }, ...soundPacks] = await Promise.all([
    import(src('core/packs/components/index.js')),
    import(src('core/packs/backgrounds/presets/index.js')),
    import(src('core/animation/presets.js')),
    import(src('core/packs/animations/index.js')),
    import(src('cards/schemas/filter-params-schemas.js')),
    import(src('core/packs/lcards-default-sound-scheme.js')),
    import(src('core/packs/builtin-msd.js')),
    import(src('core/packs/themes/tokens/lcardsDefaultTokens.js')),
    import(src('core/themes/paletteInjector.js')),
    // Every built-in pack that ships audio assets (their keys are what `sounds:` takes).
    import(src('core/packs/lcards-beeps-pack.js')),
    import(src('core/packs/lcards-alerts-pack.js')),
    import(src('core/packs/lcards-power-pack.js')),
  ]);
  const audioPacks = [BUILTIN_SOUNDS_PACK, ...soundPacks.map(m => Object.values(m).find(v => v?.audio_assets))].filter(Boolean);
  animations.registerBuiltinAnimationPresets();

  const sorted = (list) => [...new Set(list)].sort();
  const componentsByType = {};
  for (const [name, c] of Object.entries(components)) {
    const type = c.metadata?.type ?? 'unknown';
    (componentsByType[type] ??= []).push(name);
  }
  for (const type of Object.keys(componentsByType)) componentsByType[type].sort();
  // With `component:` set, a card's `preset:` names one of that component's own presets.
  const componentPresets = Object.fromEntries(Object.entries(components)
    .filter(([, c]) => c.presets)
    .map(([name, c]) => [name, sorted(Object.keys(c.presets))]));

  return {
    $comment: `LCARdS ${pkg.version}: built-in names a config can refer to. Generated by scripts/generate-llm-schema.js; do not hand-edit. User packs can add more at runtime.`,
    lcards_version: pkg.version,
    button_presets: sorted(BUILTIN_OPTIONS.buttonPresets),
    slider_presets: sorted(BUILTIN_OPTIONS.sliderPresets),
    components: componentsByType,
    component_presets: componentPresets,
    animation_presets: sorted(listAnimationPresets()),
    background_presets: sorted(Object.keys(BACKGROUND_PRESETS)),
    filters: sorted(Object.keys(FILTER_PARAMS_SCHEMAS)),
    sound_events: sorted(Object.values(BUILTIN_SOUNDS_PACK.sound_schemes).flatMap(s => Object.keys(s))),
    sound_schemes: sorted(Object.keys(BUILTIN_SOUNDS_PACK.sound_schemes)),
    sound_assets: sorted(audioPacks.flatMap(p => Object.keys(p.audio_assets))),
    msd_backgrounds: sorted(Object.keys(BUILTIN_MSD_SVG_PACK.svg_assets).map(k => `builtin:${k}`)),
    text_positions: [...BUILTIN_OPTIONS.positionEnum],
    theme_tokens: sorted(flattenKeys(lcardsDefaultTokens)),
    theme_token_open_prefixes: [...THEME_PATH_ALLOWED_PREFIXES],
    // CSS variables the HA-LCARS theme defines, without `--` (for `var(--lcars-...)`).
    ha_lcars_vars: haLcars.vars,
    ha_lcars_commit: haLcars.source.commit,
    // The LCARdS palette the integration injects as `--lcards-<name>` on every page.
    lcards_palette_vars: sorted(Object.keys(GREEN_ALERT_PALETTE).map(k => `lcards-${k}`)),
  };
}
