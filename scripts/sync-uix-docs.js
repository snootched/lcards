#!/usr/bin/env node
/**
 * sync-uix-docs.js - snapshot the UIX (UI eXtension) docs pages the user skill ships
 * (scripts/build-user-skill.js puts them under references/uix/).
 *
 *   scripts/data/uix/meta.json   source commit and the page list
 *   scripts/data/uix/<page>.md   each page as plain markdown: front matter, images and
 *                                MkDocs syntax (admonitions, tabs, attribute lists) removed,
 *                                links to pages not shipped pointed at the UIX site
 *
 * Only the styling side LCARdS users meet through HA-LCARS: install, card-mod migration,
 * `uix:` on cards and entity rows, templates, themes, where styles land in the DOM,
 * debugging. Forge and Broker are left out.
 *
 * Reads a local checkout (--repo=<dir>, default ../uix), else shallow-clones the repo.
 * Output is committed so builds stay offline; run after UIX releases (`npm run sync:uix`).
 * `--check` exits 1 when the committed pages differ instead of writing.
 *
 * UIX: https://github.com/Lint-Free-Technology/uix. Docs prose CC BY 4.0, examples MIT.
 */
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'scripts/data/uix');
export const UIX_REPO_URL = 'https://github.com/Lint-Free-Technology/uix';
export const UIX_SITE_URL = 'https://uix.lf.technology/';

/** The pages shipped, relative to docs/source. */
export const UIX_PAGES = [
  'quick-start.md',
  'faq.md',
  'using/index.md',
  'using/cards.md',
  'using/entities.md',
  'using/templates.md',
  'using/themes.md',
  'concepts/application.md',
  'concepts/dom.md',
  'debugging/cards.md',
];

const args = process.argv.slice(2);
const repoArg = args.find(a => a.startsWith('--repo='))?.slice(7);

/**
 * One MkDocs page as plain markdown.
 * @param {string} text  page source
 * @param {string} page  its path under docs/source (for link rewriting)
 */
export function cleanUixPage(text, page) {
  let md = text.replace(/^---\n[\s\S]*?\n---\n/, '');
  const lines = md.split('\n');
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    // `!!! note "Title"` / `??? tip` admonitions and `=== "Tab"` tabs: a bold lead line,
    // then the 4-space-indented body dedented.
    const adm = line.match(/^(\s*)(?:!!!|\?\?\?\+?)\s+(\w+)(?:\s+(?:inline|end))*(?:\s+"([^"]*)")?\s*$/);
    const tab = line.match(/^(\s*)===\s+"([^"]+)"\s*$/);
    if (adm || tab) {
      const indent = (adm ?? tab)[1];
      const lead = adm ? `**${adm[3] || adm[2][0].toUpperCase() + adm[2].slice(1)}:**` : `**${tab[2]}**`;
      out.push(`${indent}${lead}`, '');
      const body = indent + '    ';
      while (i + 1 < lines.length && (lines[i + 1].startsWith(body) || !lines[i + 1].trim())) {
        // A blank line followed by unindented text ends the block.
        if (!lines[i + 1].trim() && !(lines[i + 2] ?? '').startsWith(body)) break;
        out.push(indent + lines[++i].slice(body.length));
      }
      continue;
    }
    out.push(line);
  }
  md = out.join('\n')
    .replace(/!\[[^\]]*\]\([^)]*\)(\{[^}]*\})?/g, '')
    .replace(/<img\b[^>]*>/gi, '')
    .replace(/^\[\]\([^)]*\)\s*$/gm, '') // badge links whose image was removed
    .replace(/\{\s*(?:width|height|align)=[^}]*\}/g, '')
    .replace(/\]\(\/([^)\s]*)\)/g, `](${UIX_SITE_URL}$1)`) // site-absolute links
    .replace(/\s*—\s*/g, ': ') // LCARdS text carries no em dashes
    .replace(/\]\(((?!https?:|#|mailto:)[^)\s]+?\.md)(#[^)\s]*)?\)/g, (_, href, hash = '') => {
      const target = posix.normalize(posix.join(posix.dirname(page), href));
      if (UIX_PAGES.includes(target)) return `](${href}${hash})`;
      return `](${UIX_SITE_URL}${target.replace(/(index)?\.md$/, '')}${hash})`;
    })
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n');
  return md.trim() + '\n';
}

function openRepo() {
  const local = resolve(ROOT, repoArg ?? '../uix');
  if (existsSync(join(local, 'docs/source'))) return { dir: local, where: local, cleanup: () => {} };
  const dir = mkdtempSync(join(tmpdir(), 'lcards-uix-'));
  execFileSync('git', ['clone', '--quiet', '--depth', '1', `${UIX_REPO_URL}.git`, dir], { stdio: 'inherit' });
  return { dir, where: UIX_REPO_URL, cleanup: () => rmSync(dir, { recursive: true, force: true }) };
}

async function main() {
  const repo = openRepo();
  try {
    const [sha, date] = execFileSync('git', ['-C', repo.dir, 'log', '-1', '--format=%H %cs'], { encoding: 'utf8' }).trim().split(' ');
    const files = {
      'meta.json': JSON.stringify({
        $comment: 'Generated by scripts/sync-uix-docs.js; do not hand-edit. Run npm run sync:uix after UIX releases.',
        source: { repo: UIX_REPO_URL, site: UIX_SITE_URL, commit: sha, date, license: 'Docs prose CC BY 4.0, examples MIT (c) Lint-Free Technology' },
        pages: UIX_PAGES,
      }, null, 1) + '\n',
    };
    for (const page of UIX_PAGES) files[page] = cleanUixPage(readFileSync(join(repo.dir, 'docs/source', page), 'utf8'), page);

    if (args.includes('--check')) {
      const strip = (t) => t.replace(/"commit": "[^"]*"|"date": "[^"]*"/g, '');
      const stale = Object.entries(files).filter(([n, t]) => !existsSync(join(OUT_DIR, n)) || strip(readFileSync(join(OUT_DIR, n), 'utf8')) !== strip(t)).map(([n]) => n);
      if (stale.length) {
        console.error(`❌ UIX docs snapshot is stale (${stale.join(', ')}) against ${repo.where}. Run npm run sync:uix.`);
        process.exit(1);
      }
      console.log(`✅ UIX docs snapshot matches ${repo.where}`);
      return;
    }
    rmSync(OUT_DIR, { recursive: true, force: true });
    for (const [name, text] of Object.entries(files)) {
      mkdirSync(dirname(join(OUT_DIR, name)), { recursive: true });
      writeFileSync(join(OUT_DIR, name), text);
    }
    const kb = Object.values(files).reduce((n, t) => n + Buffer.byteLength(t), 0) / 1024;
    console.log(`✅ UIX ${sha.slice(0, 7)} (${date}) from ${repo.where}: ${UIX_PAGES.length} pages, ${kb.toFixed(0)} KB`);
  } finally {
    repo.cleanup();
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
