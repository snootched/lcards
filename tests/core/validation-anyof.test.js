/**
 * CoreValidationService: anyOf support.
 *
 * The chart schema declares `sources` with `anyOf` (and no top-level `type`).
 * The validator only understood `oneOf`, so every chart with `sources:` failed
 * with 'Field "sources" must be , got array' and would not render.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { CoreValidationService } from '../../src/core/validation-service/index.js';
import { getChartSchema } from '../../src/cards/schemas/chart-schema.js';

const service = () => new CoreValidationService({ cacheResults: false });

test('chart config generated by Chart Studio (sources: [series_1]) validates', () => {
    const config = {
        type: 'custom:lcards-chart',
        chart_type: 'line',
        sources: ['series_1'],
        data_sources: {
            series_1: {
                entity: 'light.tv',
                attribute: 'state',
                history: { preload: true, hours: 72 },
                name: 'Series 1',
                type: 'line',
                yaxis: 0,
            },
        },
    };
    const result = service().validate(config, getChartSchema());
    const sourcesErrors = result.errors.filter(e => e.field === 'sources');
    assert.deepEqual(sourcesErrors, [], JSON.stringify(sourcesErrors));
});

test('object-form sources with a buffer selector validate', () => {
    const result = service().validate(
        { type: 'custom:lcards-chart', sources: [{ datasource: 'temp', buffer: 'main' }] },
        getChartSchema(),
    );
    assert.deepEqual(result.errors.filter(e => e.field === 'sources'), []);
});

test('anyOf still rejects a value that matches no option', () => {
    const schema = { type: 'object', properties: { v: { anyOf: [{ type: 'array' }, { type: 'number' }] } } };
    const result = service().validate({ v: 'nope' }, schema);
    assert.equal(result.valid, false);
    assert.equal(result.errors[0]?.field, 'v');
});

test('template strings are not pattern-checked (they are evaluated at render time)', async () => {
    const { getButtonSchema } = await import('../../src/cards/schemas/button-schema.js');
    const { isTemplateString } = await import('../../src/utils/template-string.js');
    for (const value of ["[[[ return 'red' ]]]", "{{ 'red' }}", '{% if x %}red{% endif %}', '{variables.accent}']) {
        assert.equal(isTemplateString(value), true, value);
        const result = service().validate({ type: 'custom:lcards-button', style: { card: { color: { background: value } } } }, getButtonSchema({}));
        // Regression: documented colour templates warned "Format validation failed".
        assert.deepEqual([...result.errors, ...result.warnings].map(e => e.message), [], value);
    }
    for (const value of ['#ff9900', 'var(--x)', 'red', 'theme:colors.ui.primary']) assert.equal(isTemplateString(value), false, value);
    const bad = service().validate({ type: 'custom:lcards-button', style: { card: { color: { background: 'not a colour' } } } }, getButtonSchema({}));
    assert.ok([...bad.errors, ...bad.warnings].some(e => e.message === 'Format validation failed'), 'literals are still checked');
});
